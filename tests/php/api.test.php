declare(strict_types=1);

// api.php over HTTP, against a real database. The requests are the ones the
// page makes, and then the ones a hostile page or a typo would make. Each
// check of what happened reads the database straight through PDO, not through
// the viewer, so the viewer cannot vouch for itself.

