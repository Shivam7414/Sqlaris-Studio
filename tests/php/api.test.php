            foreach ($find->fetchAll(PDO::FETCH_COLUMN) as $id) {
                $pdo->exec($driver === 'pgsql' ? 'select pg_terminate_backend('.(int) $id.')' : 'kill '.(int) $id);
            }
        }
    };
