/**
 * The tests for one server. $pdo is a connection of the tests' own to the
 * test database, $db the id the page uses for it. $connect opens another
 * connection of the tests' own, to any database on the server, and $signIn
 * gives a second browser that is signed in. $settings is this server's entry
 * in the config, for db-child.php, which the tests start as a process of its
 * own when something has to go on while the viewer answers.
 *
 * @param  callable(string): PDO  $connect
 * @param  callable(): TestClient  $signIn
 */
function api_tests(string $tag, string $driver, TestClient $c, string $db, PDO $pdo, callable $connect, callable $signIn, array $settings): void
{
    $q = $driver === 'pgsql' ? fn ($n) => '"'.str_replace('"', '""', $n).'"' : fn ($n) => '`'.str_replace('`', '``', $n).'`';
    $count = fn (string $table = 'items') => (int) $pdo->query('select count(*) from '.$q($table))->fetchColumn();
    $cell = fn (string $column, int $id, string $table = 'items') => $pdo->query('select '.$q($column).' from '.$q($table).' where id = '.$id)->fetchColumn();
    $items = ['db' => $db, 'table' => ['name' => 'items']];
    $rows = fn (array $extra = []) => $c->ok('rows', $items + $extra);
    $names = function (array $answer): array {
        $at = array_search('name', array_column($answer['table']['columns'], 'name'), true);

        return array_map(fn ($row) => $row[$at], $answer['rows']);
    };

    // What the database says about itself, for the tests that make and drop things of their own.
    $schema = $driver === 'pgsql' ? "'public'" : 'database()';
    $tablesOf = fn (PDO $on, bool $baseOnly = false): array => $on->query("select table_name as name from information_schema.tables where table_schema = {$schema}"
        .($baseOnly ? " and table_type = 'BASE TABLE'" : '').' order by table_name')->fetchAll(PDO::FETCH_COLUMN);
    $hasTable = fn (string $name): bool => in_array($name, $tablesOf($pdo), true);
    $columnsOf = function (string $table) use ($pdo, $schema): array {
        $read = $pdo->prepare("select column_name as name from information_schema.columns where table_schema = {$schema} and table_name = ? order by ordinal_position");
        $read->execute([$table]);

        return $read->fetchAll(PDO::FETCH_COLUMN);
    };
    $columnInfo = function (string $table, string $name) use ($pdo, $schema): ?array {
        $read = $pdo->prepare("select is_nullable as nullable, data_type as type, character_maximum_length as len from information_schema.columns
            where table_schema = {$schema} and table_name = ? and column_name = ?");
        $read->execute([$table, $name]);

        return $read->fetch(PDO::FETCH_ASSOC) ?: null;
    };
    $commentOf = function (string $table, string $column) use ($pdo, $driver): ?string {
        $read = $driver === 'pgsql'
            ? $pdo->prepare('select col_description(a.attrelid, a.attnum) from pg_attribute a where a.attrelid = ?::regclass and a.attname = ?')
            : $pdo->prepare('select column_comment from information_schema.columns where table_schema = database() and table_name = ? and column_name = ?');
        $read->execute([$driver === 'pgsql' ? 'public.'.$table : $table, $column]);
        $comment = $read->fetchColumn();

        return $comment === false || $comment === '' ? null : $comment;
    };
    $indexesOf = function (PDO $on, string $table) use ($driver): array {
        $read = $on->prepare($driver === 'pgsql'
            ? "select indexname as name from pg_indexes where schemaname = 'public' and tablename = ?"
            : 'select distinct index_name as name from information_schema.statistics where table_schema = database() and table_name = ?');
        $read->execute([$table]);

        return $read->fetchAll(PDO::FETCH_COLUMN);
    };
    $dropTables = function (string ...$names) use ($pdo, $q): void {
        foreach ($names as $name) {
            $pdo->exec('drop table if exists '.$q($name));
        }
    };
    // Whether the server has a database of that name. It asks over a connection of its own, so it still works
    // after a test has ended $pdo.
    $hasDatabase = function (string $name) use ($connect, $driver): bool {
        $ask = $connect(TEST_DATABASE)->prepare($driver === 'pgsql'
            ? 'select count(*) from pg_database where datname = ?'
            : 'select count(*) from information_schema.schemata where schema_name = ?');
        $ask->execute([$name]);

        return (int) $ask->fetchColumn() > 0;
    };
    // How many sessions the server has under this id.
    $sessions = fn (int $id): int => (int) $pdo->query($driver === 'pgsql'
        ? "select count(*) from pg_stat_activity where pid = {$id}"
        : "select count(*) from information_schema.processlist where id = {$id}")->fetchColumn();
    $sessionId = fn (PDO $on): int => (int) $on->query($driver === 'pgsql' ? 'select pg_backend_pid()' : 'select connection_id()')->fetchColumn();
    // Rows of the tests' own in items, put in through $pdo and taken out again by name, so the fixtures stay as they are.
    $addItems = function (string ...$names) use ($pdo): array {
        $ids = [];

        foreach ($names as $name) {
            $pdo->prepare('insert into items (name) values (?)')->execute([$name]);
            $find = $pdo->prepare('select id from items where name = ?');
            $find->execute([$name]);
            $ids[$name] = (int) $find->fetchColumn();
        }

        return $ids;
    };
    $removeItems = function (array $names) use ($pdo): void {
        $delete = $pdo->prepare('delete from items where name = ?');

        foreach ($names as $name) {
            $delete->execute([$name]);
        }
    };
    $present = fn (array $ids): array => array_map('intval', $pdo->query('select id from items where id in ('.implode(', ', array_map('intval', $ids)).') order by id')->fetchAll(PDO::FETCH_COLUMN));

    // Reading

    test("{$tag} rows come back with their count", function () use ($rows) {
        $r = $rows();
        same(5, $r['total']);
        same(5, count($r['rows']));
    });

    test("{$tag} every screen's data loads", function () use ($c, $db, $items) {
        $tags = ['db' => $db, 'table' => ['name' => 'item_tags']];

        $tables = $c->ok('tables', ['db' => $db]);
        $names = array_column($tables['tables'], 'name');
        check(in_array('items', $names, true) && in_array('cheap_items', $names, true), 'tables: '.implode(', ', $names));
        check($tables['info']['maintenance'] !== [], 'the upkeep this system offers');

        $structure = $c->ok('structure', $items);
        same(['id', 'name', 'note', 'qty', 'mood', 'double_qty'], array_column($structure['table']['columns'], 'name'));
        same(true, $structure['table']['columns'][5]['readonly'], 'double_qty is filled by the database');
        same(['happy', 'sad'], $structure['table']['columns'][4]['options'] ?? ['happy', 'sad'], 'the enum values');
        check(count($structure['indexes']) >= 2, 'the primary key and items_name_idx');
        same('item_tags', $structure['table']['refs'][0]['tbl'] ?? null, 'item_tags points here');

        $fk = $c->ok('structure', $tags);
        same('items', $fk['table']['fks'][0]['tbl'] ?? null, 'item_tags points at items');
        check($c->ok('structure', ['db' => $db, 'table' => ['name' => 'cheap_items']])['view'] !== null, 'a view shows its query');

        same(2, $c->ok('refs', $items + ['row' => ['id' => '1']])['refs'][0]['count']);
        same(5, (int) $c->ok('values', $items + ['col' => 'qty'])['stats']['total']);
        check($c->ok('lookup', $items + ['col' => 'id', 'q' => 'app'])['items'] !== [], 'a foreign key search finds apple');
        check(count($c->ok('schema', ['db' => $db])['tables']) >= 5, 'the SQL editor gets the tables');
        check(count($c->ok('diagram', ['db' => $db])['tables']) >= 5, 'the diagram gets the tables');
        check(isset($c->ok('health', ['db' => $db])['findings']), 'health');
        check(isset($c->ok('activity', ['db' => $db])['sessions']), 'activity');

        $found = $c->ok('find_id', ['db' => $db, 'value' => '1'])['found'];
        $hit = fn (string $table, string $column) => array_values(array_filter($found, fn ($f) => $f['table']['name'] === $table && $f['column'] === $column))[0] ?? null;
        same('apple', $hit('items', 'id')['label'] ?? null, 'find_id names the row its primary key holds');
        same(2, $hit('item_tags', 'item_id')['rows'] ?? null, 'find_id finds item 1 in both of its tags');
        same('fk', $hit('item_tags', 'item_id')['role'] ?? null, 'item_tags.item_id is a foreign key');
        same(null, $hit('items', 'name'), 'a plain text column is not searched');
        $c->refused('find_id', ['db' => $db, 'value' => ''], 'Type the id');

        $op = $tables['info']['maintenance'][1]['op'];
        check(isset($c->ok('maintain', $items + ['op' => $op])['after']), "maintain {$op}");
        $c->refused('maintain', $items + ['op' => 'drop'], 'no such upkeep');
    });

    // Views are kept in a file of the viewer's own, so the checks read that file.
    test("{$tag} a diagram view is saved, comes back with the diagram, and is deleted", function () use ($c, $db) {
        $onDisk = fn () => json_decode((string) file_get_contents($c->server->views), true);
        $saved = $c->ok('save_view', ['db' => $db, 'view' => [
            'name' => '  Items  ',
            'tables' => ['s.items', 's.item_tags', 's.items', 42],
            'at' => ['s.items' => [10.4, -20], 's.item_tags' => ['x', 1], 's.gone' => [1, 2]],
            'layout' => 'flow',
            'detail' => 'names',
        ]])['views'];
        same(['Items'], array_column($saved, 'name'));
        $view = $onDisk()[$db][0];
        same(['s.items', 's.item_tags'], $view['tables']);
        same(['s.items' => [10, -20]], $view['at'], 'a place that is not two numbers, or of a table not in the view, is dropped');
        same(['flow', 'names'], [$view['layout'], $view['detail']]);
        same($saved, $c->ok('diagram', ['db' => $db])['views']);

        $c->ok('save_view', ['db' => $db, 'view' => ['name' => 'items', 'tables' => ['s.items'], 'layout' => 'drop', 'detail' => 'x']]);
        $views = $onDisk()[$db];
        same(1, count($views), 'the same name in another case replaces the view');
        same(['s.items'], $views[0]['tables']);
        same(['flow', 'keys'], [$views[0]['layout'], $views[0]['detail']], 'a layout or detail not on the list falls back');

        same([], $c->ok('delete_view', ['db' => $db, 'name' => 'ITEMS'])['views']);
        check(! isset($onDisk()[$db]), 'nothing is kept for the database');
    });

    test("{$tag} a view needs a name and a table, and its text is only ever text", function () use ($c, $db, $count) {
        $c->refused('save_view', ['db' => $db, 'view' => ['name' => '   ', 'tables' => ['s.items']]], 'Give the view a name');
        $c->refused('save_view', ['db' => $db, 'view' => 'not a view'], 'Give the view a name');
        $c->refused('save_view', ['db' => $db, 'view' => ['name' => 'Empty', 'tables' => []]], 'at least one table');
        $c->refused('save_view', ['db' => $db, 'view' => ['name' => str_repeat('x', 61), 'tables' => ['s.items']]], 'up to 60 characters');
        $c->refused('save_view', ['db' => 'nowhere/x', 'view' => ['name' => 'X', 'tables' => ['s.items']]], 'not on the list');
        $c->refused('delete_view', ['db' => 'nowhere/x', 'name' => 'X'], 'not on the list');

        $sql = "x'); drop table items; --";
        same([$sql], $c->ok('save_view', ['db' => $db, 'view' => ['name' => $sql, 'tables' => [$sql]]])['views'][0]['tables']);
        same(5, $count(), 'nothing in a view reaches the database');
        same([], $c->ok('delete_view', ['db' => $db, 'name' => $sql])['views']);
    });

    test("{$tag} a views file that does not read is never written over", function () use ($c, $db) {
        $broken = "{\"other/db\": [{\"name\": \"Kept\", \"tables\": [\"s.a\"]},]}\n";
        file_put_contents($c->server->views, $broken);
        $c->refused('save_view', ['db' => $db, 'view' => ['name' => 'New', 'tables' => ['s.items']]], 'Could not read diagram-views.json');
        $c->refused('delete_view', ['db' => $db, 'name' => 'Kept'], 'Could not read diagram-views.json');
        same($broken, file_get_contents($c->server->views), 'the file is as it was');
        unlink($c->server->views);
    });

    test("{$tag} an export gives every matching row, in each format", function () use ($c, $items) {
        foreach (['csv' => 'apple', 'json' => '"name":"apple"', 'sql' => "'apple'"] as $format => $expect) {
            $r = $c->api('export', $items + ['format' => $format, 'filters' => [['col' => 'name', 'op' => 'eq', 'value' => 'apple']]]);
            same(200, $r['status'], $format);
            check(str_contains($r['body'], $expect), "{$format} has apple: ".substr($r['body'], 0, 200));
            check(! str_contains($r['body'], 'banana'), "{$format} keeps to the filter");
        }
    });

    test("{$tag} a table name with SQL in it is looked up, not run", function () use ($c, $db, $count) {
        foreach (['items; drop table items; --', 'items" where 1=1 --', 'items` --', "items'"] as $name) {
            $c->refused('rows', ['db' => $db, 'table' => ['name' => $name]], 'There is no table');
        }

        $c->refused('rows', ['db' => $db, 'table' => ['schema' => 'x; drop table items', 'name' => 'items']], 'There is no table');
        same(5, $count());
    });

    test("{$tag} a table whose real name has the quote character in it works", function () use ($c, $db, $pdo, $q, $driver) {
        // The character each system quotes names with, inside the name itself.
        $mark = $driver === 'pgsql' ? '"' : '`';
        $table = "odd {$mark}name{$mark} table";
        $column = "odd {$mark}col{$mark}";
        $odd = ['db' => $db, 'table' => ['name' => $table]];
        same(1, $c->ok('rows', $odd)['total']);
        $c->ok('update', $odd + ['keys' => [['id' => '1']], 'changes' => [$column => 'y']]);
        same('y', $pdo->query('select '.$q($column).' from '.$q($table))->fetchColumn());
    });

    test("{$tag} a filter or sort on a column that is not there is refused", function () use ($c, $items) {
        $c->refused('rows', $items + ['filters' => [['col' => 'name; drop table items', 'op' => 'eq', 'value' => 'x']]], 'has no column');
        $c->refused('rows', $items + ['sort' => ['col' => 'id desc; drop table items', 'dir' => 'asc']], 'has no column');
    });

    test("{$tag} a filter operator must be one of the known ones", function () use ($c, $items) {
        $c->refused('rows', $items + ['filters' => [['col' => 'name', 'op' => '= 1 or 1=1 --', 'value' => 'x']]], 'Unknown filter');
    });

    test("{$tag} a sort direction other than desc sorts ascending", function () use ($rows, $names) {
        $asc = $names($rows(['sort' => ['col' => 'name', 'dir' => 'asc']]));
        same($asc, $names($rows(['sort' => ['col' => 'name', 'dir' => 'desc; drop table items']])));
        same(array_reverse($asc), $names($rows(['sort' => ['col' => 'name', 'dir' => 'desc']])));
    });

    test("{$tag} a filter value is bound, so quotes in it match nothing extra", function () use ($rows) {
        same(0, $rows(['filters' => [['col' => 'name', 'op' => 'eq', 'value' => "x' or '1'='1"]]])['total']);
        same(0, $rows(['filters' => [['col' => 'name', 'op' => 'contains', 'value' => "' or 1=1 --"]]])['total']);
        same(1, $rows(['filters' => [['col' => 'name', 'op' => 'in', 'value' => "apple, x') or ('1'='1"]]])['total']);
        same(0, $rows(['filters' => [['col' => 'qty', 'op' => 'gt', 'value' => '100']]])['total']);
    });

    test("{$tag} a search for % or _ finds those characters, not everything", function () use ($rows, $names) {
        same(['50% off'], $names($rows(['search' => '50%'])));
        same(['under_score'], $names($rows(['search' => '_'])));
        same(0, $rows(['search' => "'; drop table items; --"])['total']);
    });

    test("{$tag} paging is clamped, and a page size cannot carry SQL", function () use ($rows) {
        same(1000, $rows(['perPage' => 999999])['perPage']);
        same(1, $rows(['perPage' => '1; drop table items'])['perPage']);
        same(1, $rows(['page' => -5])['page']);
    });

    test("{$tag} a database that is not on the list cannot be opened", function () use ($c, $driver) {
        $c->refused('tables', ['db' => ($driver === 'pgsql' ? 'pg' : 'my').'/'.($driver === 'pgsql' ? 'postgres' : 'mysql')], 'not on the list');
        $c->refused('tables', ['db' => 'nope/items'], 'not on the list');
    });

    // Writing

    test("{$tag} a value with SQL in it is stored exactly as typed", function () use ($c, $items, $count, $pdo) {
        $before = $count();
        $name = "Robert'); drop table items; --";
        $note = "\" ` \\ ' ; -- /* */ \\x00";
        $c->ok('insert', $items + ['values' => ['name' => $name, 'note' => $note, 'qty' => '7']]);
        same($before + 1, $count());
        $row = $pdo->query('select name, note from items where qty = 7')->fetch(PDO::FETCH_ASSOC);
        same(['name' => $name, 'note' => $note], $row);
    });

    test("{$tag} an update changes one row and no other", function () use ($c, $items, $cell) {
        $c->ok('update', $items + ['keys' => [['id' => '2']], 'changes' => ['qty' => '20']]);
        same('20', (string) $cell('qty', 2));
        same('1', (string) $cell('qty', 1));
        same('3', (string) $cell('qty', 3));
    });

    test("{$tag} a row key with SQL in it is refused, and no row changes", function () use ($c, $items, $pdo) {
        $before = $pdo->query('select id, qty from items order by id')->fetchAll(PDO::FETCH_KEY_PAIR);
        // PostgreSQL refuses these as integers. MySQL would read most of them as 1,
        // and a DELETE would then remove row 1, so the viewer refuses them first.
        foreach (['1 or 1=1', '1abc', '1; drop table items', '', '1.0e0x'] as $key) {
            $c->refused('update', $items + ['keys' => [['id' => $key]], 'changes' => ['qty' => '99']]);
            $c->refused('delete', $items + ['keys' => [['id' => $key]]]);
        }

        same($before, $pdo->query('select id, qty from items order by id')->fetchAll(PDO::FETCH_KEY_PAIR));
    });

    test("{$tag} a change to a column that is not there, or that the database fills, is refused", function () use ($c, $items, $cell) {
        $c->refused('update', $items + ['keys' => [['id' => '1']], 'changes' => ['qty = 0, name' => 'x']], 'has no column');
        $c->refused('update', $items + ['keys' => [['id' => '1']], 'changes' => ['double_qty' => '9']], 'filled by the database');
        same('1', (string) $cell('qty', 1));
    });

    test("{$tag} an update needs the row key, and a row that is gone saves nothing", function () use ($c, $items) {
        $c->refused('update', $items + ['keys' => [[]], 'changes' => ['qty' => '0']], 'row key is missing');
        $c->refused('update', $items + ['keys' => [['id' => '999999']], 'changes' => ['qty' => '0']], 'not there any more');
        $c->refused('update', $items + ['keys' => [], 'changes' => ['qty' => '0']], 'at least one row');
        $c->refused('delete', $items + ['keys' => array_fill(0, 1001, ['id' => '1'])], 'At most 1000');
    });

    test("{$tag} a table without a primary key cannot be edited row by row", function () use ($c, $db, $count) {
        $c->refused('update', ['db' => $db, 'table' => ['name' => 'no_pk'], 'keys' => [['a' => '1']], 'changes' => ['a' => '2']], 'no primary key');
        $c->refused('delete', ['db' => $db, 'table' => ['name' => 'no_pk'], 'keys' => [['a' => '1']]], 'no primary key');
        same(1, $count('no_pk'));
    });

    test("{$tag} a paste over many rows is kept whole or not at all", function () use ($c, $items, $cell) {
        $c->refused('update_each', $items + ['items' => [
            ['key' => ['id' => '1'], 'changes' => ['qty' => '10']],
            ['key' => ['id' => '3'], 'changes' => ['qty' => '-1']],
        ]]);
        same('1', (string) $cell('qty', 1), 'the first row must be rolled back');
    });

    test("{$tag} an import with one bad row keeps none, and names the row", function () use ($c, $items, $count) {
        $before = $count();
        $c->refused('import', $items + ['columns' => ['name', 'qty'], 'rows' => [['kiwi', '1'], ['bad', '-5'], ['lime', '2']]], 'Row 2');
        $c->refused('import', $items + ['columns' => ['name', 'qty'], 'rows' => [['kiwi', '1'], ['lime', 'two']]], 'Row 2');
        same($before, $count());
        $c->refused('import', $items + ['columns' => ['double_qty'], 'rows' => [['1']]], 'filled by the database');
        $c->refused('import', $items + ['columns' => ['name; drop table items'], 'rows' => [['x']]], 'has no column');
        $c->ok('import', $items + ['columns' => ['name', 'qty'], 'rows' => [['kiwi', '1'], ['lime', '2']]]);
        same($before + 2, $count());
    });

    // The next tests work on rows of their own, put in through $pdo and taken out again, because the tests
    // after them read the fixture rows by their ids.

    test("{$tag} a delete removes the rows whose keys are sent, and the rows that point at them", function () use ($c, $items, $pdo, $count, $addItems, $removeItems, $present) {
        $names = ['probe gone one', 'probe gone two', 'probe kept one', 'probe kept two'];
        $ids = $addItems(...$names);

        try {
