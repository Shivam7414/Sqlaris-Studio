            $protectInPage($db, $extraId);
            $unlock($extraId, TEST_EXTRA_DATABASE);
            $r = $c->api('layout', ['layout' => ['protected' => [$extraId]]]);
            same([423, $db], [$r['status'], $r['json']['db'] ?? null], 'the locked one is named');
            same([$db, $extraId], $saved(), 'neither came off');
            $c->ok('layout', ['layout' => ['protected' => [$db]]]);
            same([$db], $saved(), 'the unlocked one came off, and the other stayed');
        } finally {
            $unprotect();
            $lockAgain($db, $extraId);
        }
    });

    test("{$tag} copying a protected database is refused while it is locked, and making an empty one is not", function () use ($c, $lockedId, $connect, $hasDatabase, $tablesOf, $unlock, $lockAgain, $makeDatabase, $dropDatabase, $makeProbes) {
        $inside = $makeDatabase(TEST_LOCKED_DATABASE);

        try {
            $makeProbes($inside);

            // The config protects it, so it is locked from the start.
            $r = $c->api('create_database', ['db' => $lockedId, 'name' => TEST_EXTRA_DATABASE, 'copy' => true]);
            same(423, $r['status'], 'a copy: '.substr($r['body'], 0, 200));
            same([true, $lockedId], [$r['json']['protected'] ?? null, $r['json']['db'] ?? null]);
            check(str_contains((string) ($r['json']['error'] ?? ''), 'is protected'), 'the message: '.($r['json']['error'] ?? ''));
            same(false, $hasDatabase(TEST_EXTRA_DATABASE), 'nothing was made');

            // An empty database is not a copy of anything.
            $c->ok('create_database', ['db' => $lockedId, 'name' => TEST_EXTRA_DATABASE]);
            same(true, $hasDatabase(TEST_EXTRA_DATABASE), 'an empty one is made');
            same([], $tablesOf($connect(TEST_EXTRA_DATABASE)), 'and it is empty');
            $dropDatabase(TEST_EXTRA_DATABASE);

            // Unlocked, the copy is made, with the tables of the original. PostgreSQL ends the sessions in the original to do it.
            $unlock($lockedId, TEST_LOCKED_DATABASE);
            $inside = null;
            $c->ok('create_database', ['db' => $lockedId, 'name' => TEST_EXTRA_DATABASE, 'copy' => true]);
            check(in_array('probe_locked', $tablesOf($connect(TEST_EXTRA_DATABASE)), true), 'unlocked, the copy has the tables');
        } finally {
            $lockAgain($lockedId);
            $inside = null;
            $dropDatabase(TEST_EXTRA_DATABASE);
            $dropDatabase(TEST_LOCKED_DATABASE);
        }
    });

    // Making and dropping databases. The config lists sqlaris_test and one more name, so that is the only one to make.

    test("{$tag} a new database is empty and opens in the page, and is dropped only when its name is typed back", function () use ($c, $db, $connect, $tablesOf, $hasDatabase) {
        $id = explode('/', $db, 2)[0].'/'.TEST_EXTRA_DATABASE;
        same(false, $hasDatabase(TEST_EXTRA_DATABASE), 'the run starts without it');

        $r = $c->ok('create_database', ['db' => $db, 'name' => TEST_EXTRA_DATABASE]);

        same($id, $r['id']);
        same(true, $hasDatabase(TEST_EXTRA_DATABASE));
        same([], $tablesOf($connect(TEST_EXTRA_DATABASE)), 'a new database has no tables');
        same([], $c->ok('tables', ['db' => $id])['tables'], 'the page can open it');
        $c->refused('create_database', ['db' => $db, 'name' => TEST_EXTRA_DATABASE], 'exist');

        $c->refused('drop_database', ['db' => $id, 'confirm' => strtoupper(TEST_EXTRA_DATABASE)], 'Type the database name');
        $c->refused('drop_database', ['db' => $id, 'confirm' => TEST_DATABASE], 'Type the database name');
        $c->refused('drop_database', ['db' => $id], 'Type the database name');
        same(true, $hasDatabase(TEST_EXTRA_DATABASE), 'a wrong name drops nothing');

        $c->ok('drop_database', ['db' => $id, 'confirm' => TEST_EXTRA_DATABASE]);
        same(false, $hasDatabase(TEST_EXTRA_DATABASE));
    });

    test("{$tag} a database the config keeps off the list is neither made nor dropped from here", function () use ($c, $db, $hasDatabase) {
        $name = TEST_DATABASE.'_unlisted';
        $server = explode('/', $db, 2)[0];

        $c->refused('create_database', ['db' => $db, 'name' => $name], 'off the list');
        same(false, $hasDatabase($name), 'it was not made');
        $c->refused('create_database', ['db' => 'nope/x', 'name' => TEST_EXTRA_DATABASE], 'not on the list');
        same(false, $hasDatabase(TEST_EXTRA_DATABASE), 'a database is not made from one that is not on the list either');
        $c->refused('drop_database', ['db' => "{$server}/{$name}", 'confirm' => $name], 'not on the list');
    });

    // Keep this test last. PostgreSQL copies only a database nobody is in, so the viewer ends every other
    // session in the test database first, and that ends $pdo too. What the test reads from the original it
    // reads before the call, and after it the test goes on with connections opened after the call.
    test("{$tag} a database made as a copy has the tables, indexes and rows of the original", function () use ($c, $db, $pdo, $q, $connect, $tablesOf, $indexesOf, $hasDatabase) {
        same(false, $hasDatabase(TEST_EXTRA_DATABASE), 'the run starts without it');
        $tables = $tablesOf($pdo, true);
        check(count($tables) >= 4, 'the fixture tables are there: '.implode(', ', $tables));
        $rows = [];

        foreach ($tables as $table) {
            $rows[$table] = $pdo->query('select * from '.$q($table).' order by 1')->fetchAll(PDO::FETCH_NUM);
        }

        check(in_array('items_name_idx', $indexesOf($pdo, 'items'), true), 'the original has the index the copy is checked for');

        $r = $c->ok('create_database', ['db' => $db, 'name' => TEST_EXTRA_DATABASE, 'copy' => true]);

        same(explode('/', $db, 2)[0].'/'.TEST_EXTRA_DATABASE, $r['id']);
        $copy = $connect(TEST_EXTRA_DATABASE);
        same([], array_diff($tables, $tablesOf($copy, true)), 'every table of the original is in the copy');

        foreach ($tables as $table) {
            same($rows[$table], $copy->query('select * from '.$q($table).' order by 1')->fetchAll(PDO::FETCH_NUM), "{$table} has the same rows in the copy");
        }

        check(in_array('items_name_idx', $indexesOf($copy, 'items'), true), 'the index came along');

        $copy = null;
        $c->ok('drop_database', ['db' => $r['id'], 'confirm' => TEST_EXTRA_DATABASE]);
        same(false, $hasDatabase(TEST_EXTRA_DATABASE));
    });
}

/** The requests that must be refused before any database is touched. */
function http_tests(TestServer $server, string $username, string $password): void
{
    test('api.php answers only POST with the page\'s own header', function () use ($server, $username, $password) {
        $c = new TestClient($server);
        $c->signIn($username, $password);
        same(400, $c->request('GET', '/api.php')['status']);
        same(400, $c->api('databases', [], ['X-Sqlaris' => ''])['status']);
        same(400, $c->request('POST', '/api.php', 'not json', ['X-Sqlaris' => '1'])['status']);
        same(200, $c->api('databases')['status']);
    });

    test('api.php refuses a browser that has not signed in', function () use ($server) {
        $c = new TestClient($server);
        same(401, $c->api('databases')['status']);
    });

    test('a Host header that is not this computer is refused, signed in or not', function () use ($server, $username, $password) {
        $c = new TestClient($server);
        $c->signIn($username, $password);
        same(403, $c->api('databases', [], ['Host' => 'evil.example'])['status']);
        same(403, $c->request('GET', '/', '', ['Host' => 'evil.example'])['status']);
    });

    test('a wrong password or a missing form token does not sign in', function () use ($server, $username, $password) {
        $c = new TestClient($server);
        check(str_contains($c->signIn($username, $password.'x')['body'], 'do not match'), 'wrong password');
        same(401, $c->api('databases')['status']);

        $c = new TestClient($server);
        $c->request('GET', '/');
        $page = $c->request('POST', '/', http_build_query(['username' => $username, 'password' => $password]), ['Content-Type' => 'application/x-www-form-urlencoded']);
        check(str_contains($page['body'], 'form expired'), 'no token');
        same(401, $c->api('databases')['status']);
    });

    test('the router serves the page, the API and assets, and nothing else', function () use ($server) {
        $c = new TestClient($server);

        foreach (['/.env', '/config.php', '/layout.json', '/diagram-views.json', '/src/lib.php', '/assets/../config.php', '/tests/php/run.php'] as $path) {
            same(404, $c->request('GET', $path)['status'], $path);
        }

        same(200, $c->request('GET', '/assets/app.js')['status']);
    });
}
